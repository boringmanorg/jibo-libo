// Saves the homepage's eight showcase reviews so the full review feed loads only on demand.
// Re-run after editing review data: bun scripts/generateHomeFeaturedReviews.ts
import { writeFileSync } from 'node:fs';
import { pickFloating, defaultReviews } from '../src/components/v2/home/HomeReviews';
const cards = pickFloating(defaultReviews());
writeFileSync('src/data/homeFeaturedReviews.ts', `// Generated by scripts/generateHomeFeaturedReviews.ts — verbatim, do not edit by hand.
import type { R } from '@/components/v2/home/ReviewCard';
export const HOME_FEATURED_REVIEWS: R[] = ${JSON.stringify(cards, null, 2)};
`);
console.log(cards.length, 'cards');
